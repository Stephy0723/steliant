const getWordRegExp = (str) => {
  const clean = escapeRegExp(str)
  const prefix = /^\w/.test(str) ? '\\b' : ''
  const suffix = /\w$/.test(str) ? '\\b' : ''
  return new RegExp(prefix + clean + suffix, 'giu')
}

const strip = (value) => value.normalize('NFD').replace(/[̀-ͯ]/g, '')
const ALL_PHRASES = { ...PHRASES, ...EXTRA_PHRASES }

// Generated (npm run i18n:generate) + reviewed strings are whole UI texts, so
// they only apply on an exact match of the full text node / attribute. They
// never become regexes: ~3k extra patterns run on every node would make the
// DOM pass slow, and short entries ("Ver") would splice into longer strings.
const exactKey = (value) => strip(value).replace(/\s+/g, ' ').trim()
const exactMap = new Map(
  Object.entries({ ...GENERATED_TRANSLATIONS, ...REVIEW_TRANSLATION_OVERRIDES })
    .map(([from, to]) => [exactKey(from), to]),
)
const ALL_WORDS = { ...WORDS, ...EXTRA_WORDS }

const phraseEntries = Object.entries(ALL_PHRASES)
  .sort(([a], [b]) => b.length - a.length)
  .map(([from, to]) => [getWordRegExp(from), to])
// ES only needs to undo English source copy ("Admin panel"); Spanish source
// comes back from LangContext's originalText. So the reverse pass is exact
// whole-string only -- substring regexes rewrote real Spanish sentences
// ("Riot Games" -> "Riot Juegos", "online" -> "En Linea") and stripped accents.
const reverseExactMap = new Map(
  Object.entries(ALL_PHRASES).map(([from, to]) => [exactKey(to).toLowerCase(), PRETTY_ES[to] || from]),
)

// Single generic words are NEVER spliced into a larger, otherwise-unmatched string
// (that produced Spanglish like "Open GG, asistente virtual" from "Abrir GG, asistente
// virtual" — only "Abrir" matched, the rest stayed in Spanish). They only apply when
// they are the *entire* trimmed value, e.g. a text node that is just "Guardar" or
// "miembros" — the normal shape JSX produces when a literal is its own text node.
const wordMap = new Map(Object.entries(ALL_WORDS).map(([from, to]) => [strip(from).trim().toLowerCase(), to]))
const reverseWordMap = new Map(Object.entries(ALL_WORDS).map(([from, to]) => [strip(to).trim().toLowerCase(), from]))

export function translateLegacy(value, targetLang = 'en') {
  if (!value || !value.trim()) return value
  if (/^(ES|EN)$/i.test(value.trim())) return value.toUpperCase()
  const [, leading = '', , trailing = ''] = value.match(/^(\s*)([\s\S]*?)(\s*)$/) || []
  if (targetLang === 'es') {
    const key = exactKey(value).toLowerCase()
    const exact = reverseExactMap.get(key) ?? reverseWordMap.get(key)
    // Same word both ways ("Élite", "Región"): keep the original casing/accents.
    if (exact === undefined || strip(exact).toLowerCase() === key) return value
    return leading + exact + trailing
  }
  const exact = exactMap.get(exactKey(value))
  if (exact !== undefined) return leading + exact + trailing
  const stripped = strip(value)
  let result = stripped
  for (const [pattern, to] of phraseEntries) result = result.replace(pattern, to)
  if (result === stripped) {
    // No phrase matched anything: try a whole-string word match instead of
    // falling back to word-boundary substring replacement.
    const key = stripped.trim().toLowerCase()
    if (wordMap.has(key)) result = leading + wordMap.get(key) + trailing
  }
  // Nothing matched at all: return the original value untouched instead of the
  // diacritics-stripped search copy, so accented Spanish text (e.g. "posición",
  // "qué") never gets silently mangled when it needed no translation.
  return result === stripped ? value : result
}

function escapeRegExp(value) {
  return strip(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

